    private void llenarTablaLR0() {
        if (analLR0 == null) return;

        // Construimos encabezados
        int numTerm = analLR0.vt2.length + 1;   // + "$"
        int numNoTerm = analLR0.vn.length;

        String[] columnas = new String[1 + numTerm + numNoTerm];
        columnas[0] = "Edo";

        int idx = 1;
        for (String t : analLR0.vt2) {
            columnas[idx++] = t;
        }
        columnas[idx++] = "$";           // último terminal
        for (String nt : analLR0.vn) {
            columnas[idx++] = nt;
        }

        javax.swing.table.DefaultTableModel model =
                new javax.swing.table.DefaultTableModel(columnas, 0);

        // Rellenar filas
        for (int i = 0; i < analLR0.numEstados; i++) {
            Object[] fila = new Object[columnas.length];
            fila[0] = i; // número de estado

            int col = 1;

            // ACTION (terminales)
            for (int j = 0; j < numTerm; j++) {
                fila[col++] = analLR0.actionLR0[i][j];
            }

            // GOTO (no terminales)
            for (int j = 0; j < numNoTerm; j++) {
                int destino = analLR0.gotoLR0[i][j];
                fila[col++] = (destino >= 0) ? destino : "";
            }

            model.addRow(fila);
        }

        tablaLR0.setModel(model);
    }
    
    private void llenarTablaIrA() {
        if (analLR0 == null) return;

        javax.swing.table.DefaultTableModel model =
                new javax.swing.table.DefaultTableModel(
                        new Object[]{"Edo", "IrA(Edo, Símbolo)", "Items destino"}, 0);

        for (int k = 0; k < analLR0.numRenglonesIrA; k++) {
            Inf_IrA info = analLR0.resultIrA[k];
            if (info == null) continue;

            // la fila inicial tiene irA_Sj = -1 (solo describe S0), también la mostramos
            String edoOrigen  = (info.irA_Sj >= 0) ? String.valueOf(info.irA_Sj) : "";
            String irAString;

            if (info.irA_Sj >= 0) {
                irAString = "IrA(" + info.irA_Sj + ", " + info.irA_Simbolo + ") = " + info.Si;
            } else {
                irAString = "S0";
            }

            String items = info.ConjuntoItems; // ya lo llenas en CrearTablaLR0

            model.addRow(new Object[]{ edoOrigen, irAString, items });
        }

        tablaIrA.setModel(model);
    }

    

