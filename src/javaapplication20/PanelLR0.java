    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
                                                
        if (analLR0 == null) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Primero crea la tabla LR(0).",
                    "Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        javax.swing.table.TableModel model = tablaTerminales.getModel();
        int filas = model.getRowCount();

        for (int i = 0; i < filas; i++) {
            Object simbObj  = model.getValueAt(i, 0); // columna Terminal
            Object tokenObj = model.getValueAt(i, 1); // columna Token

            if (simbObj == null) continue;
            String simb = simbObj.toString().trim();
            if (simb.isEmpty()) continue;

            int token = -1;
            if (tokenObj != null && !tokenObj.toString().trim().isEmpty()) {
                try {
                    token = Integer.parseInt(tokenObj.toString().trim());
                } catch (NumberFormatException e) {
                    // si no es número, lo ignoramos o mostramos aviso
                    javax.swing.JOptionPane.showMessageDialog(
                            this,
                            "Token inválido en la fila " + i + " para el terminal '" + simb + "'.",
                            "Advertencia",
                            javax.swing.JOptionPane.WARNING_MESSAGE);
                    continue;
                }
            }

            // Buscar el índice del terminal en el arreglo vt2 de AnalizadorLR0
            for (int j = 0; j < analLR0.vt2.length; j++) {
                if (analLR0.vt2[j].equals(simb)) {
                    analLR0.vt3[j] = token;      // guardamos token numérico
                    analLR0.vt[j].token = token; // opcional: también en el SimbolG
                    break;
                }
            }
        }

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Tokens asignados a los terminales.",
                "Listo",
                javax.swing.JOptionPane.INFORMATION_MESSAGE);
    

    }//GEN-LAST:event_jButton2ActionPerformed

